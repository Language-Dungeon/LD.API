export function descriptorOf(code: AiErrorCode): AiErrorDescriptor {
  return AI_ERROR_CATALOG[code];
}

export function isAiErrorCode(value: unknown): value is AiErrorCode {
  return typeof value === "string" && value in AI_ERROR_CATALOG;
}

export function codesByDomain(domain: AiErrorDomain): AiErrorCode[] {
  return (Object.keys(AI_ERROR_CATALOG) as AiErrorCode[]).filter((code) => AI_ERROR_CATALOG[code].domain === domain);
}
